// WP-I1: search (spec 5.5, UX-IN-25, UX-ST-02) and the hierarchy tree (5.3.2, UX-AC-02) in the browser.

import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'
import { INFO_CARD_SELECTOR, SEARCH_SELECTOR, eventually, openReady, readT, urlParam } from './helpers.ts'

const HEART = '0000114'

async function selParam(page: Page): Promise<string | null> {
  return eventually(() => Promise.resolve(urlParam(page, 'sel')), (v) => v !== null, 3000)
}

test.describe('search', () => {
  test('slash focuses the field, Enter on "heart" selects the heart and clears the field', async ({ page }) => {
    await openReady(page, '/?t=24&v=lat')
    await page.keyboard.press('/')
    const field = page.locator(SEARCH_SELECTOR).first()
    await expect(field).toBeFocused()
    await field.fill('heart')
    const list = page.getByRole('listbox', { name: 'Search structures' })
    await expect(list).toBeVisible()
    const first = list.getByRole('option').first()
    await expect(first).toContainText('heart')
    await expect(first).toContainText('Cardiovascular')
    await expect(first).toContainText('19 hpf to adult')
    await expect(first).toHaveAttribute('aria-selected', 'true')
    await page.keyboard.press('Enter')
    await expect(page.locator(INFO_CARD_SELECTOR).first()).toContainText(/heart/i)
    expect(await selParam(page)).toContain(HEART)
    await expect(field).toHaveValue('')
    await expect(field).not.toBeFocused()
  })

  test('Ctrl+K focuses the field; arrows move the active row; one Escape closes, clears and leaves', async ({ page }) => {
    await openReady(page, '/?t=24&v=lat')
    await page.keyboard.press('Control+k')
    const field = page.locator(SEARCH_SELECTOR).first()
    await expect(field).toBeFocused()
    await field.fill('e')
    const options = page.getByRole('listbox', { name: 'Search structures' }).getByRole('option')
    expect(await options.count()).toBeGreaterThan(1)
    await expect(options.nth(0)).toHaveAttribute('aria-selected', 'true')
    await page.keyboard.press('ArrowDown')
    await expect(options.nth(1)).toHaveAttribute('aria-selected', 'true')
    await expect(field).toHaveAttribute('aria-activedescendant', /atlas-search-list-ZFA:\d{7}/)
    await page.keyboard.press('ArrowUp')
    await expect(options.nth(0)).toHaveAttribute('aria-selected', 'true')
    // UX-ST-02: one press closes the list, clears the field and returns focus to the viewer.
    await page.keyboard.press('Escape')
    await expect(page.getByRole('listbox', { name: 'Search structures' })).toHaveCount(0)
    await expect(field).toHaveValue('')
    await expect(field).not.toBeFocused()
  })

  test('an absent structure shows the clock text and Jump moves t to the first appearance, then selects', async ({ page }) => {
    await openReady(page, '/?t=10&v=lat')
    await page.keyboard.press('/')
    await page.locator(SEARCH_SELECTOR).first().fill('heart')
    const row = page.getByRole('listbox', { name: 'Search structures' }).getByRole('option').first()
    await expect(row).toContainText('absent now, from 19 hpf')
    await row.getByTestId('search-jump').click()
    const t = await eventually(() => readT(page), (v) => v !== null && Math.abs(v - 19.15) < 0.01)
    expect(t).not.toBeNull()
    expect(Math.abs((t as number) - 19.15)).toBeLessThan(0.01)
    expect(await selParam(page)).toContain(HEART)
  })

  test('Shift+Enter on the active row jumps and selects', async ({ page }) => {
    await openReady(page, '/?t=10&v=lat')
    await page.keyboard.press('/')
    await page.locator(SEARCH_SELECTOR).first().fill('heart')
    await expect(page.getByRole('listbox', { name: 'Search structures' })).toBeVisible()
    await page.keyboard.press('Shift+Enter')
    const t = await eventually(() => readT(page), (v) => v !== null && Math.abs(v - 19.15) < 0.01)
    expect(Math.abs((t as number) - 19.15)).toBeLessThan(0.01)
    expect(await selParam(page)).toContain(HEART)
  })

  test('selecting an absent structure keeps t and offers a Jump toast', async ({ page }) => {
    await openReady(page, '/?t=10&v=lat')
    await page.keyboard.press('/')
    await page.locator(SEARCH_SELECTOR).first().fill('heart')
    await page.keyboard.press('Enter')
    expect(await selParam(page)).toContain(HEART)
    expect(await readT(page)).toBe(10)
    const jump = page.getByRole('button', { name: /^Jump to 19.1 hpf$/ })
    await expect(jump).toBeVisible()
    await jump.click()
    const t = await eventually(() => readT(page), (v) => v !== null && Math.abs(v - 19.15) < 0.01)
    expect(Math.abs((t as number) - 19.15)).toBeLessThan(0.01)
  })

  test('no match shows the notice and three selectable suggestions; "Show all N" expands a long list', async ({ page }) => {
    await openReady(page, '/?t=24&v=lat')
    const field = page.locator(SEARCH_SELECTOR).first()
    await page.keyboard.press('/')
    await field.fill('xyzzyq')
    const options = page.getByRole('listbox', { name: 'Search structures' }).getByRole('option')
    await expect(options.first()).toContainText("No structure matches 'xyzzyq'. Search also covers ZFA synonyms and ids.")
    await expect(options.first()).toHaveAttribute('aria-disabled', 'true')
    await expect(options).toHaveCount(4)
    await options.nth(1).click()
    expect(await selParam(page)).toMatch(/^\d{7}$/)
    await page.keyboard.press('/')
    await field.fill('a')
    await expect(options).toHaveCount(9)
    const more = page.getByTestId('search-more')
    await expect(more).toHaveText(/^Show all \d+$/)
    const n = Number((await more.innerText()).replace(/\D/g, ''))
    await more.click()
    await expect(options).toHaveCount(n)
    await expect(more).toHaveCount(0)
  })
})

test.describe('tree', () => {
  test('renders the ARIA tree with system rows, counts and the present filter on', async ({ page }) => {
    await openReady(page, '/?t=24&v=lat')
    const tree = page.getByRole('tree', { name: 'Structures' })
    await expect(tree).toHaveAttribute('aria-multiselectable', 'true')
    const systems = page.getByTestId('tree-system')
    const shown = await systems.count()
    expect(shown).toBeGreaterThanOrEqual(4)
    expect(shown).toBeLessThan(15)
    await expect(systems.first()).toHaveAttribute('aria-level', '1')
    await expect(systems.first()).toHaveAttribute('aria-expanded', 'true')
    await expect(systems.first()).toHaveAttribute('aria-posinset', '1')
    await expect(systems.first()).toHaveAttribute('aria-setsize', String(shown))
    await expect(systems.first().locator('.badge').first()).toHaveText(/^\d+ \/ \d+$/)
    const filter = page.getByTestId('tree-filter')
    await expect(filter).toBeChecked()
    await filter.uncheck()
    await expect(systems).toHaveCount(15)
    await expect(page.getByRole('treeitem', { name: 'Reproductive', exact: true })).toHaveCount(1)
    // At 0 hpf the heart (from 19 hpf) is absent: its system row hides with the filter on and shows as absent with it off.
    await openReady(page, '/?t=0&v=lat')
    await expect(page.locator('[data-key="sys:early_embryo"]')).toHaveCount(1)
    await expect(page.locator('[data-key="sys:cardiovascular"]')).toHaveCount(0)
    await page.getByTestId('tree-filter').uncheck()
    await expect(page.locator('[data-key="sys:cardiovascular"] > .tree-row')).toHaveAttribute('data-present', 'false')
    await expect(page.locator('[data-key="sys:early_embryo"] > .tree-row')).toHaveAttribute('data-present', 'true')
  })

  test('keyboard: Down moves, Right expands, Left collapses, Enter selects; the eye hides', async ({ page }) => {
    await openReady(page, '/?t=24&v=lat')
    const cardio = page.locator('[data-key="sys:cardiovascular"]')
    await expect(cardio).toHaveAccessibleName('Cardiovascular')
    await expect(cardio).toHaveAttribute('aria-expanded', 'true')
    // A click on a system row focuses it and toggles its expansion (no record to select).
    await cardio.locator('#tree-name-sys\\:cardiovascular').click()
    await expect(cardio).toBeFocused()
    await expect(cardio).toHaveAttribute('aria-expanded', 'false')
    await page.keyboard.press('ArrowRight')
    await expect(cardio).toHaveAttribute('aria-expanded', 'true')
    await expect(cardio).toBeFocused()
    await page.keyboard.press('ArrowRight')
    // The single "cardiovascular system" wrapper folds into the system row (R13), so the first row
    // below it is the level-2 group "cardinal system".
    const group = page.locator('[data-key="ZFA:0000096"]')
    await expect(group).toBeFocused()
    await expect(group).toHaveAccessibleName('cardinal system')
    await expect(group).toHaveAttribute('aria-level', '2')
    await expect(group).toHaveAttribute('aria-expanded', 'false')
    await page.keyboard.press('ArrowRight')
    await expect(group).toHaveAttribute('aria-expanded', 'true')
    await page.keyboard.press('ArrowRight')
    const heart = page.locator('[data-key="ZFA:0000114"]')
    await expect(group.locator('[role="group"] > [role="treeitem"]').first()).toBeFocused()
    // Type-ahead: "hea" moves to the first row that starts with it.
    await page.keyboard.type('hea', { delay: 50 })
    await expect(heart).toBeFocused()
    await expect(heart).toHaveAccessibleName('heart')
    await expect(heart).toHaveAttribute('aria-level', '2')
    // The tree owns its keys: t did not move and the x-ray did not toggle while a row had focus.
    expect(await readT(page)).toBe(24)
    expect(urlParam(page, 'xr')).toBeNull()
    await page.keyboard.press('Enter')
    expect(await selParam(page)).toContain(HEART)
    await expect(heart).toHaveAttribute('aria-selected', 'true')
    await expect(page.locator(INFO_CARD_SELECTOR).first()).toContainText(/heart/i)
    await page.keyboard.press('Tab')
    const eye = heart.getByRole('button', { name: 'Hide heart' })
    await expect(eye).toBeFocused()
    await page.keyboard.press('Space')
    await expect(heart.getByRole('button', { name: 'Show heart' })).toHaveAttribute('aria-pressed', 'false')
    expect(await readT(page)).toBe(24)
    const hide = await eventually(() => Promise.resolve(urlParam(page, 'hide')), (v) => v !== null && v.includes(HEART), 3000)
    expect(hide).toContain(HEART)
    await page.keyboard.press('Shift+Tab')
    await expect(heart).toBeFocused()
    // Left on a collapsed row climbs to the nearest ancestor with a row; the folded wrapper has none.
    await page.keyboard.press('ArrowLeft')
    await expect(cardio).toBeFocused()
    await page.keyboard.press('ArrowLeft')
    await expect(cardio).toHaveAttribute('aria-expanded', 'false')
    await page.keyboard.press('Home')
    await expect(page.getByTestId('tree-system').first()).toBeFocused()
  })

  test('a selection made from search reveals and marks its tree row', async ({ page }) => {
    await openReady(page, '/?t=24&v=lat&sel=0000114')
    const heart = page.locator('[data-key="ZFA:0000114"]')
    await expect(heart).toBeVisible()
    await expect(heart).toHaveAttribute('aria-selected', 'true')
    await expect(heart).toHaveAttribute('tabindex', '0')
  })
})
